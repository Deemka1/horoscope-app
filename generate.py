tomorrow = today + timedelta(days=1)

# Астрономические данные на сегодня
subject_today = AstrologicalSubjectFactory.from_birth_data(
    name="Today", year=today.year, month=today.month, day=today.day,
    hour=12, minute=0, lng=37.6173, lat=55.7558, tz_str="Europe/Moscow", online=False
)

# Астрономические данные на завтра (для проверки смены Луны)
subject_tomorrow = AstrologicalSubjectFactory.from_birth_data(
    name="Tomorrow", year=tomorrow.year, month=tomorrow.month, day=tomorrow.day,
    hour=12, minute=0, lng=37.6173, lat=55.7558, tz_str="Europe/Moscow", online=False
)

moon_sign_today = subject_today.moon.sign
moon_sign_tomorrow = subject_tomorrow.moon.sign
mercury_retrograde = subject_today.mercury.retrograde

# Определяем индекс недели (0-3) и месяца (0-11) для ротации шаблонов
week_index = today.isocalendar()[1] % 4
month_index = (today.month - 1) % 4 # Берем 4 варианта на месяц для простоты

horoscope = {}
