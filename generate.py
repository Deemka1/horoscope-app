    sign_upper = sign.capitalize()
    
    # Определяем индекс для ротации (0-3)
    week_num = datetime.now().isocalendar()[1]
    month_num = datetime.now().month
    
    if period == "today":
        focus_list = DAILY_FOCUS[sign_upper]
        idx = week_num % 4  # Меняется каждую неделю
        focus = focus_list[idx]
        do = "Сфокусируйся на этом сегодня."
        avoid = "Отвлеченности и распыления."
        
    elif period == "tomorrow":
        focus_list = DAILY_FOCUS[sign_upper]
        idx = (week_num + 1) % 4
        focus = focus_list[idx]
        do = "Подготовься к этому заранее."
        avoid = "Импровизации в последний момент."
        
    elif period == "this_week":
        focus_list = WEEKLY_FOCUS[sign_upper]
        idx = week_num % 4
        focus = focus_list[idx]
        do = "Выдели время на это в течение недели."
        avoid = "Откладывания важных решений."
        
    elif period == "next_week":
        focus_list = WEEKLY_FOCUS[sign_upper]
        idx = (week_num + 1) % 4
        focus = focus_list[idx]
        do = "Запланируй это на следующую неделю."
        avoid = "Спешки и суеты."
        
    elif period == "this_month":
        focus_list = MONTHLY_FOCUS[sign_upper]
        idx = (month_num - 1) % 4
        focus = focus_list[idx]
        do = "Сделай это своим приоритетом месяца."
        avoid = "Распыления на второстепенное."
        
    elif period == "next_month":
        focus_list = MONTHLY_FOCUS[sign_upper]
        idx = month_num % 4
        focus = focus_list[idx]
        do = "Начни подготовку уже сейчас."
        avoid = "Игнорирования деталей."
        
    elif period == "this_year":
        focus = YEARLY_FOCUS[sign_upper]
        do = "Держи этот фокус в течение всего года."
        avoid = "Отклонения от выбранного курса."
    else:
        focus = do = avoid = ""
    
    # Добавляем предупреждение о Меркурии, если он ретроградный
    mercury_note = ""
    if astro_data["mercury_retrograde"]:
        if period in ["today", "tomorrow", "this_week", "next_week"]:
            mercury_note = " ВНИМАНИЕ: Меркурий ретроградный! Перепроверяй документы, не подписывай важные контракты, не покупай технику."
