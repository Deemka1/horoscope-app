def get_astro_data(days_offset):
    target_date = datetime.now() + timedelta(days=days_offset)
    subject = AstrologicalSubjectFactory.from_birth_data(
        name="Future", year=target_date.year, month=target_date.month, day=target_date.day,
        hour=12, minute=0, lng=37.6173, lat=55.7558, tz_str="Europe/Moscow", online=False
    )
    return {
        "sun_sign": subject.sun.sign,
        "moon_sign": subject.moon.sign,
        "moon_position": subject.moon.position,
        "mercury_sign": subject.mercury.sign,
        "mercury_retrograde": subject.mercury.retrograde,
        "venus_sign": subject.venus.sign,
        "mars_sign": subject.mars.sign,
        "date_str": target_date.strftime('%d.%m.%Y')
    }

def get_text_for_period(sign, period):
    sign_lower = sign.lower()
    day_of_year = datetime.now().timetuple().tm_yday
    week_num = datetime.now().isocalendar()[1]
    month_num = datetime.now().month
    
    if period == "today":
        idx = day_of_year % 5
        return {"focus": DAILY_TEXTS[sign_lower]['focus'][idx], "do": DAILY_TEXTS[sign_lower]['do'][idx], "avoid": DAILY_TEXTS[sign_lower]['avoid'][idx]}
    elif period == "tomorrow":
        idx = (day_of_year + 1) % 5
        return {"focus": DAILY_TEXTS[sign_lower]['focus'][idx], "do": DAILY_TEXTS[sign_lower]['do'][idx], "avoid": DAILY_TEXTS[sign_lower]['avoid'][idx]}
    elif period == "this_week":
        idx = week_num % 4
        return {"focus": "Недельный фокус", "do": WEEKLY_TEXTS[sign_lower][idx], "avoid": "Распыления на второстепенное"}
    elif period == "next_week":
        idx = (week_num + 1) % 4
        return {"focus": "Недельный фокус", "do": WEEKLY_TEXTS[sign_lower][idx], "avoid": "Спешки и суеты"}
    elif period == "this_month":
        idx = (month_num - 1) % 4
        return {"focus": "Месячная тема", "do": MONTHLY_TEXTS[sign_lower][idx], "avoid": "Отклонения от курса"}
    elif period == "next_month":
        idx = month_num % 4
        return {"focus": "Месячная тема", "do": MONTHLY_TEXTS[sign_lower][idx], "avoid": "Игнорирования деталей"}
    elif period == "this_year":
        return {"focus": "Годовая тема", "do": YEARLY_TEXTS[sign_lower], "avoid": "Отклонения от пути"}
    
    return {"focus": "", "do": "", "avoid": ""}

